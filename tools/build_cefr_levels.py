"""Rebuilds cefr_levels.json from the two Open Language Profiles CSVs (not shipped; fetch them yourself):

    python tools/build_cefr_levels.py cefrj-vocabulary-profile-1.5.csv octanove-vocabulary-profile-c1c2-1.0.csv cefr_levels.json

CEFR-J covers A1-B2, Octanove C1-C2. Headwords like "color/colour" become two words; a word listed
at several levels (one per part of speech) keeps its lowest, and CEFR-J wins over Octanove.
"""
import csv
import json
import sys

LEVELS = ("A1", "A2", "B1", "B2", "C1", "C2")

META = {
    "about": "Word to CEFR level list used by the level badge (word_levels.py). Generated by tools/build_cefr_levels.py.",
    "sources": [
        {
            "levels": "A1-B2",
            "name": "CEFR-J Wordlist Version 1.5 (as distributed in openlanguageprofiles/olp-en-cefrj, cefrj-vocabulary-profile-1.5.csv)",
            "citation": "The CEFR-J Wordlist Version 1.5. Compiled by Yukio Tono, Tokyo University of Foreign Studies. Retrieved from http://www.cefr-j.org/download.html on 1/20/2020.",
            "licence": "Free for research and commercial use provided the dataset is cited. Copyright: Tono Laboratory, Tokyo University of Foreign Studies.",
        },
        {
            "levels": "C1-C2",
            "name": "Octanove Vocabulary Profile C1/C2 Version 1.0 (openlanguageprofiles/olp-en-cefrj, octanove-vocabulary-profile-c1c2-1.0.csv)",
            "citation": "Octanove Vocabulary Profile C1/C2 (ver 1.0), created by Octanove Labs, from Open Language Profiles.",
            "licence": "Creative Commons Attribution-ShareAlike 4.0 International (CC BY-SA 4.0), https://creativecommons.org/licenses/by-sa/4.0/. The C1/C2 words in this file are redistributed under the same licence.",
        },
    ],
}


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            level = row["CEFR"].strip().upper()
            if level not in LEVELS:
                continue
            for word in row["headword"].split("/"):
                word = word.strip().lower()
                if word:
                    yield word, level


def main(cefrj_csv, octanove_csv, out_path):
    best = {}
    for path in (cefrj_csv, octanove_csv):
        for word, level in read(path):
            if word not in best or LEVELS.index(level) < LEVELS.index(best[word]):
                best[word] = level
    words = {lvl: sorted(w for w, l in best.items() if l == lvl) for lvl in LEVELS}
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump({"_meta": META, "words": words}, f, ensure_ascii=False, indent=0)
        f.write("\n")
    print({lvl: len(ws) for lvl, ws in words.items()})


if __name__ == "__main__":
    main(*sys.argv[1:4])
